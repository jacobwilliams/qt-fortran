    !> A thread that runs `work(data)` when started (Qt's QThread::create). `data`
    !> is stored by reference: it needs the TARGET attribute and must outlive the
    !> thread. Give the thread a parent (e.g. the main window), or delete it.
    function QThread_create(work, data, parent) result(thread)
        procedure(qt_slot) :: work
        class(*), intent(inout), target, optional :: data
        class(QObject), intent(in), optional :: parent
        type(QThread) :: thread
        type(thread_task), pointer :: task
        allocate(task)
        task%work => work
        if (present(data)) task%data => data
        call qtf_set_task_runner(c_funloc(qtf_thread_task))
        call thread%attach(qtf_qthread_create(c_loc(task), qtf_ptr(parent)))
    end function QThread_create

    !> Called by the shim: run (op 0, in the worker thread) or free (op 1) a task.
    subroutine qtf_thread_task(ptr, op) bind(C)
        type(c_ptr), value :: ptr
        integer(c_int), value :: op
        type(thread_task), pointer :: task
        call c_f_pointer(ptr, task)
        if (op == 1) then
            deallocate(task)
        else if (associated(task%data)) then
            call task%work(task%data)
        else
            call task%work()
        end if
    end subroutine qtf_thread_task

